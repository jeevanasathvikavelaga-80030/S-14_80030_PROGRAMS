import java.util.*;
public class Pattern4 
{
 public static void main(String[] args)
 {
  int n = 5;
  for (int j = 0; j < n; j++)
  {
   for (int i = 0; i < i; i++)
   {
    System.out.print(" ");
   }
    for (int i = n - j; i > 0; i--)
   {
    System.out.print("* ");
   }
    System.out.println();
  }
 }
}

